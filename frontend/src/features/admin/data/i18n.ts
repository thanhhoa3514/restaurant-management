export type AdminT = (key: string, ...args: Array<string | number>) => string

export function makeAdminT(lang: Lang): AdminT {
  return (key, ...args) => {
    const value = ADMIN_DICT[lang][key]
    if (typeof value === 'function') return value(...(args as never[]))
    return value ?? key
  }
}
